//! Compare a conditional PUT with a small, document-bearing WAL commit.
//! BENCH_URL must name a disposable, dedicated prefix; all created keys are removed.
use bf_storage::{CreateResult, Storage, StorageConfig};
use bf_wal::{Wal, WalEntry, WriteBatch};
use serde_json::json;
use std::{error::Error, time::Instant};

fn p50(samples: &mut [f64]) -> f64 {
    samples.sort_by(f64::total_cmp);
    samples[(samples.len() - 1) / 2]
}
#[tokio::main]
async fn main() -> Result<(), Box<dyn Error>> {
    let url = std::env::var("BENCH_URL")?;
    if !url.contains("/dev/perf-bench/") && !url.starts_with("file://") {
        return Err("use a dedicated dev/perf-bench prefix or local file store".into());
    }
    let store = Storage::open(&StorageConfig {
        url,
        endpoint: std::env::var("BENCH_ENDPOINT").ok(),
        profile: std::env::var("BENCH_PROFILE").ok(),
        region: std::env::var("BENCH_REGION").ok(),
        ..Default::default()
    })
    .await?;
    let ns = format!("latency-{}", uuid::Uuid::new_v4());
    let wal = Wal::new(store.clone(), &ns)?;
    let mut puts = Vec::new();
    let mut commits = Vec::new();
    let run = async {
        for seq in 1..=23 {
            let now = chrono::Utc::now();
            let batch = WriteBatch {
                upserts: vec![serde_json::from_value(json!({"id":seq,"text":"small durable write","vector":[0.1,0.2,0.3,0.4]}))?],
                deletes: vec![], schema: serde_json::from_value(json!({"id":{"type":"uint"},"text":{"type":"string"},"vector":{"type":"[4]f32"}}))?,
                distance_metric: Default::default(), created_at: now, updated_at: now,
            };
            let entry = WalEntry::new(vec![batch]);
            let encoded = entry.encode()?;
            let tick = Instant::now();
            assert_eq!(store.create(&format!("ns/{ns}/control/{seq}"), encoded).await?, CreateResult::Created);
            let put_ms = tick.elapsed().as_secs_f64() * 1000.0;
            let tick = Instant::now();
            assert_eq!(wal.append(seq, &entry).await?, CreateResult::Created);
            if seq > 3 {
                puts.push(put_ms);
                commits.push(tick.elapsed().as_secs_f64() * 1000.0);
            }
        }
        Ok::<_, Box<dyn Error>>(())
    }.await;
    // This namespace is generated by this invocation, and has no other writers.
    for object in store.list(&format!("ns/{ns}/")).await? {
        store.delete(&object.key).await?;
    }
    run?;
    println!(
        "{}",
        serde_json::to_string_pretty(
            &json!({"samples":commits.len(),"single_put_p50_ms":p50(&mut puts),"wal_commit_p50_ms":p50(&mut commits),"wal_data_puts":1})
        )?
    );
    Ok(())
}
